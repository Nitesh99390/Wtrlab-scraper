#!/usr/bin/env node
/**
 * Assembles backend/generated/wtrlab_core.ts from the four hardened core modules.
 *
 * The core files (wtrlab_live_extractor.ts, wtrlab_catalog_and_routes.ts, wtrlab_build_gate.ts,
 * wtrlab_telegram_handlers.ts) are code *sections*: they were authored to be embedded in a larger host
 * (module-level helpers + Express routes, and class methods). They are NEVER edited. This script embeds
 * them byte-for-byte into one closure/class, exactly like test/live_wtrlab_verify.ts does when it validates
 * them, and wires in the host-side helpers (see backend/hostbase.ts, backend/util.ts, ...).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(root, 'backend', f), 'utf-8');

const extractor = read('wtrlab_live_extractor.ts');
const catalog = read('wtrlab_catalog_and_routes.ts');
const gate = read('wtrlab_build_gate.ts');
const telegram = read('wtrlab_telegram_handlers.ts');

